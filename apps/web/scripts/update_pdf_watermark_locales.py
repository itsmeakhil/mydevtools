FONT_VALUES = {
    "fontHelvetica": "Helvetica",
    "fontHelveticaBold": "Helvetica Bold",
    "fontTimes": "Times Roman",
    "fontCourier": "Courier",
}


def default_page_count() -> str:
    return "{count, plural, one {# page} other {# pages}}"


def apply_locale(path: Path, stem: str) -> None:
    with path.open(encoding="utf-8") as f:
        data = json.load(f)

    tr = L[stem]
    page_count = (
        data.get("PdfCompressor", {}).get("pageCount") or default_page_count()
    )

    data.setdefault("Navigation", {})["pdfWatermark"] = tr["nav"]
    data.setdefault("Dashboard", {}).setdefault("tools", {})["pdfWatermark"] = {
        "title": tr["dash_title"],
        "description": tr["dash_desc"],
    }

    panel: dict[str, str] = {
        "intro": tr["intro"],
        "privacyNote": tr["privacyNote"],
        "choosePdf": tr["choosePdf"],
        "reset": tr["reset"],
        "pageCount": page_count,
        "tabText": tr["tabText"],
        "tabImage": tr["tabImage"],
        "textLabel": tr["textLabel"],
        "textPlaceholder": tr["textPlaceholder"],
        "fontLabel": tr["fontLabel"],
        "sizeLabel": tr["sizeLabel"],
        "rotationLabel": tr["rotationLabel"],
        "colorLabel": tr["colorLabel"],
        "chooseImage": tr["chooseImage"],
        "imageHint": tr["imageHint"],
        "imageWidthLabel": tr["imageWidthLabel"],
        "positionLabel": tr["positionLabel"],
        "posCenter": tr["posCenter"],
        "posTl": tr["posTl"],
        "posTr": tr["posTr"],
        "posBl": tr["posBl"],
        "posBr": tr["posBr"],
        "opacityLabel": tr["opacityLabel"],
        "download": tr["download"],
        "working": tr["working"],
        "done": tr["done"],
        "invalidPdf": tr["invalidPdf"],
        "encryptedPdf": tr["encryptedPdf"],
        "stampFailed": tr["stampFailed"],
        "invalidImage": tr["invalidImage"],
        "emptyText": tr["emptyText"],
        "needImage": tr["needImage"],
    }
    for fk in FONT_KEYS:
        panel[fk] = FONT_VALUES[fk]

    data["PdfWatermark"] = panel

    with path.open("w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")


def main() -> None:
    missing = []
    for path in sorted(MESSAGES_DIR.glob("*.json")):
        stem = path.stem
        if stem not in L:
            missing.append(stem)
            continue
        apply_locale(path, stem)
    if missing:
        raise SystemExit(f"Missing translations for: {missing}")
    print(f"Updated {len(L)} locale files under {MESSAGES_DIR}")


if __name__ == "__main__":
    main()
